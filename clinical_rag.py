"""## Hybrid Retrieval (KEY PART)"""

def reciprocal_rank_fusion(ranked_lists, k=60):
    """Merge multiple ranked lists using RRF scoring."""
    scores = {}
    for ranked in ranked_lists:
        for rank, idx in enumerate(ranked):
            scores[idx] = scores.get(idx, 0) + 1 / (k + rank + 1)
    return sorted(scores, key=scores.get, reverse=True)

def hybrid_search(query, k=5):
    # --- FAISS semantic search ---
    query_embedding = embed_model.encode([query], convert_to_numpy=True)
    _, faiss_indices = index.search(np.array(query_embedding, dtype=np.float32), k)
    faiss_ranked = list(faiss_indices[0])

    # --- BM25 keyword search ---
    tokenized_query = query.lower().split()          # FIX: lowercase to match tokenized_chunks
    bm25_scores = bm25.get_scores(tokenized_query)
    bm25_ranked = list(np.argsort(bm25_scores)[::-1][:k])  # FIX: descending order

    # --- Combine via Reciprocal Rank Fusion ---
    combined_indices = reciprocal_rank_fusion([faiss_ranked, bm25_ranked])[:k]
    return [chunks[i] for i in combined_indices], combined_indices

"""## MMR (Diversity)"""

from sklearn.metrics.pairwise import cosine_similarity

def mmr(query, retrieved_chunks, lambda_param=0.7, top_k=4):
    if not retrieved_chunks:
        return []

    query_emb = embed_model.encode([query])           # shape: (1, 384)
    chunk_embs = embed_model.encode(retrieved_chunks)  # shape: (n, 384)

    selected = []
    candidate_indices = list(range(len(retrieved_chunks)))

    while len(selected) < top_k and candidate_indices:
        scores = []
        for i in candidate_indices:
            emb = chunk_embs[i].reshape(1, -1)                          # FIX: explicit reshape
            relevance = cosine_similarity(query_emb, emb)[0][0]

            if selected:
                # FIX: compare against already-selected embeddings properly
                selected_embs = chunk_embs[selected]
                diversity = max(cosine_similarity(emb, selected_embs.reshape(len(selected), -1))[0])
            else:
                diversity = 0.0

            score = lambda_param * relevance - (1 - lambda_param) * diversity
            scores.append((i, score))

        best_idx = max(scores, key=lambda x: x[1])[0]
        selected.append(best_idx)
        candidate_indices.remove(best_idx)

    return [retrieved_chunks[i] for i in selected]

"""## Reranker"""

from sentence_transformers import CrossEncoder

reranker = CrossEncoder('cross-encoder/ms-marco-MiniLM-L-6-v2')

def rerank(query, chunks):
    if not chunks:
        return []
    pairs = [[query, chunk] for chunk in chunks]
    scores = reranker.predict(pairs)
    ranked = sorted(zip(chunks, scores), key=lambda x: x[1], reverse=True)
    return [chunk for chunk, _ in ranked]


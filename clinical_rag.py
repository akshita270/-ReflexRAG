"""## Chunking (Character-based with Overlap)

"""

def chunk_text(text, chunk_size=500, overlap=100):
    """
    Splits on sentence endings so chunks don't cut mid-sentence.
    Falls back to character split only if no sentence boundary found.
    """
    sentences = re.split(r'(?<=[.?!])\s+', text)
    chunks = []
    current_chunk = ""

    for sentence in sentences:
        if len(current_chunk) + len(sentence) <= chunk_size:
            current_chunk += " " + sentence
        else:
            if current_chunk.strip():
                chunks.append(current_chunk.strip())
            # Start new chunk with overlap from end of last chunk
            overlap_text = current_chunk[-overlap:] if len(current_chunk) > overlap else current_chunk
            current_chunk = overlap_text + " " + sentence

    if current_chunk.strip():
        chunks.append(current_chunk.strip())

    return chunks

def is_valid_chunk(chunk, min_words=30):
    words = chunk.split()
    if len(words) < min_words:
        return False
    if chunk.count('...') > 3:
        return False
    if chunk.count('....') > 2:
        return False
    roman = re.findall(r'\b(i{1,3}|iv|v|vi{1,3}|ix|x)\b', chunk.lower())
    if len(roman) > 5:
        return False
    return True

